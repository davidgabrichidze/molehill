//! OpenVPN profiles that don't start from a `.ovpn` file: fetched from an
//! OpenVPN Access Server, or built from fields the user typed in.

use std::time::Duration;

use anyhow::{Result, anyhow, bail};
use base64::Engine;
use serde::{Deserialize, Serialize};

use crate::APP_VERSION;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]
#[serde(rename_all = "kebab-case")]
pub enum TlsKeyMode {
    #[default]
    None,
    TlsAuth,
    TlsCrypt,
}

/// A hand-entered OpenVPN client setup.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct ManualOvpn {
    pub host: String,
    pub port: u16,
    pub tcp: bool,
    /// PEM, one or more certificates.
    pub ca: String,
    #[serde(default)]
    pub tls_mode: TlsKeyMode,
    #[serde(default, skip_serializing_if = "String::is_empty")]
    pub tls_key: String,
    /// Extra directives, one per line (e.g. `cipher AES-256-GCM`).
    #[serde(default, skip_serializing_if = "String::is_empty")]
    pub extra: String,
}

impl ManualOvpn {
    pub fn validate(&self) -> Result<()> {
        if self.host.trim().is_empty() || self.host.contains(char::is_whitespace) {
            bail!("Enter the server address, e.g. vpn.example.com");
        }
        if self.port == 0 {
            bail!("Enter a port between 1 and 65535 (OpenVPN's default is 1194)");
        }
        if !self.ca.contains("-----BEGIN CERTIFICATE-----") {
            bail!("Paste the server's CA certificate (the text starting with -----BEGIN CERTIFICATE-----)");
        }
        if self.tls_mode != TlsKeyMode::None && !self.tls_key.contains("-----BEGIN") {
            bail!("Paste the TLS key (the text starting with -----BEGIN OpenVPN Static key)");
        }
        Ok(())
    }

    /// The client config these fields describe.
    pub fn to_config(&self) -> String {
        let mut c = String::new();
        c.push_str("# Generated by Molehill from manually entered settings\n");
        c.push_str("client\ndev tun\n");
        c.push_str(if self.tcp { "proto tcp-client\n" } else { "proto udp\n" });
        c.push_str(&format!("remote {} {}\n", self.host.trim(), self.port));
        c.push_str("resolv-retry infinite\nnobind\npersist-key\npersist-tun\n");
        c.push_str("remote-cert-tls server\nauth-user-pass\nverb 3\n");
        for line in self.extra.lines().map(str::trim).filter(|l| !l.is_empty()) {
            c.push_str(line);
            c.push('\n');
        }
        c.push_str(&format!("<ca>\n{}\n</ca>\n", self.ca.trim()));
        match self.tls_mode {
            TlsKeyMode::None => {}
            TlsKeyMode::TlsAuth => c.push_str(&format!("<tls-auth>\n{}\n</tls-auth>\nkey-direction 1\n", self.tls_key.trim())),
            TlsKeyMode::TlsCrypt => c.push_str(&format!("<tls-crypt>\n{}\n</tls-crypt>\n", self.tls_key.trim())),
        }
        c
    }
}

/// `vpn.example.com`, `vpn.example.com:943` or `https://vpn.example.com/` →
/// `https://vpn.example.com[:943]`.
pub fn server_base_url(address: &str) -> Result<String> {
    let a = address.trim().trim_end_matches('/');
    let a = a.strip_prefix("https://").or_else(|| a.strip_prefix("http://")).unwrap_or(a);
    let host = a.split('/').next().unwrap_or("");
    if host.is_empty() || host.contains(char::is_whitespace) {
        bail!("Enter the server address, e.g. vpn.example.com");
    }
    Ok(format!("https://{host}"))
}

/// Downloads the user-locked profile from an OpenVPN Access Server
/// (`/rest/GetUserlogin`, the same call OpenVPN Connect uses).
pub fn fetch_access_server_profile(address: &str, username: &str, password: &str, accept_invalid_cert: bool) -> Result<String> {
    let url = format!("{}/rest/GetUserlogin", server_base_url(address)?);
    let tls = ureq::tls::TlsConfig::builder().disable_verification(accept_invalid_cert).build();
    let agent: ureq::Agent = ureq::Agent::config_builder()
        .tls_config(tls)
        .http_status_as_error(false)
        .timeout_global(Some(Duration::from_secs(20)))
        .build()
        .into();
    let auth = base64::engine::general_purpose::STANDARD.encode(format!("{username}:{password}"));
    let mut resp = agent
        .get(&url)
        .header("Authorization", &format!("Basic {auth}"))
        .header("User-Agent", &format!("Molehill/{APP_VERSION}"))
        .call()
        .map_err(|e| {
            let msg = e.to_string();
            if msg.to_ascii_lowercase().contains("certificate") {
                anyhow!("The server's web certificate isn't trusted. If you expect that (many Access Servers use a self-signed one), turn on “Accept self-signed certificate”.")
            } else {
                anyhow!("Couldn't reach {url}: {msg}")
            }
        })?;
    let status = resp.status().as_u16();
    let body = resp.body_mut().read_to_string().unwrap_or_default();
    if status == 200 && body.contains("remote ") && body.contains("<ca>") {
        return Ok(body);
    }
    // Errors come back as <Error><Type>..</Type><Message>..</Message></Error>.
    let message = between(&body, "<Message>", "</Message>").unwrap_or_default();
    if message.contains("AUTH_FAILED") || status == 401 {
        if message.contains("CRV1") {
            bail!("This server asks for a one-time code to download profiles, which isn't supported yet. Download the .ovpn from its web portal and import the file instead.");
        }
        bail!("The server rejected the username or password.");
    }
    if status == 404 || !body.contains("remote ") {
        bail!("No OpenVPN profile at {url} (HTTP {status}). Is this an OpenVPN Access Server? Otherwise use the file or manual setup.");
    }
    bail!("The server answered HTTP {status}: {}", if message.is_empty() { "no details" } else { &message });
}

fn between(s: &str, start: &str, end: &str) -> Option<String> {
    let i = s.find(start)? + start.len();
    let j = s[i..].find(end)? + i;
    Some(s[i..j].trim().to_string())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn manual_config_is_valid_and_safe() {
        let m = ManualOvpn {
            host: "vpn.example.com".into(),
            port: 443,
            tcp: true,
            ca: "-----BEGIN CERTIFICATE-----\nX\n-----END CERTIFICATE-----".into(),
            tls_mode: TlsKeyMode::TlsAuth,
            tls_key: "-----BEGIN OpenVPN Static key V1-----\nK\n-----END OpenVPN Static key V1-----".into(),
            extra: "cipher AES-256-GCM\n\n".into(),
        };
        m.validate().unwrap();
        let cfg = m.to_config();
        assert!(cfg.contains("proto tcp-client\nremote vpn.example.com 443\n"));
        assert!(cfg.contains("</tls-auth>\nkey-direction 1"));
        assert!(cfg.contains("\ncipher AES-256-GCM\n"));
        assert!(crate::ovpn::sanitize(&cfg).is_ok());

        let evil = ManualOvpn { extra: "up calc.exe".into(), ..m };
        assert!(crate::ovpn::sanitize(&evil.to_config()).is_err());
    }

    #[test]
    fn normalizes_addresses() {
        assert_eq!(server_base_url("vpn.example.com").unwrap(), "https://vpn.example.com");
        assert_eq!(server_base_url(" https://vpn.example.com:943/admin ").unwrap(), "https://vpn.example.com:943");
        assert!(server_base_url("  ").is_err());
    }
}
